"""Retrieval eval: the same questions against the legacy KB and the restructured KB.

usage: python tools/kb_eval.py            (writes eval/results.md and eval/results_per_question.csv)

Indexes each knowledge-base version with the search engine from KBsearch (tools/kb.py, unchanged:
hashed bag-of-words + bigram + trigram vectors, exact error-code match first) and asks every
question in eval/questions.csv. Three conditions:

  before             kb/before: 4 legacy pages, several issues per page, prose steps, a stale duplicate
  after              kb/after: 10 articles, one issue each, written to ARTICLE-TEMPLATE.md
  after, no metadata kb/after with product, category, symptoms and error code removed (an ablation:
                     how much of the gain comes from the structured fields)

Deterministic: no model calls, no randomness, so every number in the README can be reproduced.
"""

from __future__ import annotations

import csv
import sys
import tempfile
from pathlib import Path
from statistics import mean

sys.path.insert(0, str(Path(__file__).resolve().parent))
import kb  # noqa: E402
from kbmd import Doc, load_dir  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
K = 3


def run_condition(docs: list[Doc], questions: list[dict]) -> list[dict]:
    by_id = {d.article.article_id: d for d in docs}
    with tempfile.TemporaryDirectory() as tmp:
        conn = kb.connect(Path(tmp) / "index.db")
        kb.sync(conn, [d.article for d in docs], source="eval")
        rows = []
        for q in questions:
            hits = kb.search(conn, q["question"], k=K)
            rows.append(score(q, [by_id[h.article_id] for h in hits], docs))
        conn.close()
    return rows


def score(q: dict, top: list[Doc], docs: list[Doc]) -> dict:
    issue = q["issue_id"]
    first = top[0] if top else None
    hit1 = bool(first and first.covers(issue))
    steps, esc = kb.parse_body(first.article.body) if first else ([], "")
    return {
        "id": q["id"], "style": q["style"], "issue_id": issue,
        "top1": first.article.title if first else "",
        "hit1": hit1,
        "hit3": any(d.covers(issue) for d in top),
        "stale1": bool(first and first.stale_for(issue)),
        "words1": first.total_words if first else 0,
        "relevant_share1": (first.issue_words(issue) / first.total_words) if hit1 else 0.0,
        "numbered_steps1": hit1 and len(steps) >= 2,
        "escalation1": hit1 and bool(esc),
        "chance1": sum(d.covers(issue) for d in docs) / len(docs),
    }


def summarise(rows: list[dict]) -> dict:
    n = len(rows)
    hits = [r for r in rows if r["hit1"]]
    return {
        "n": n,
        "hit1": sum(r["hit1"] for r in rows),
        "hit3": sum(r["hit3"] for r in rows),
        "stale1": sum(r["stale1"] for r in rows),
        "chance1": mean(r["chance1"] for r in rows),
        "words1": mean(r["words1"] for r in rows),
        "relevant_share_when_hit": mean(r["relevant_share1"] for r in hits) if hits else 0.0,
        "usable1": sum(r["hit1"] and r["numbered_steps1"] and r["escalation1"] for r in rows),
        "by_style": {s: (sum(r["hit1"] for r in rows if r["style"] == s), sum(r["style"] == s for r in rows))
                     for s in ("plain", "vague", "typo", "code")},
    }


def conditions() -> dict[str, list[Doc]]:
    return {
        "before": load_dir(ROOT / "kb" / "before"),
        "after": load_dir(ROOT / "kb" / "after"),
        "after, no metadata": load_dir(ROOT / "kb" / "after", keep_metadata=False),
    }


def main() -> int:
    with open(ROOT / "eval" / "questions.csv", encoding="utf-8", newline="") as fh:
        questions = list(csv.DictReader(fh))
    results = {name: run_condition(docs, questions) for name, docs in conditions().items()}
    sums = {name: summarise(rows) for name, rows in results.items()}
    n = len(questions)
    pct = lambda a, b=n: f"{a}/{b} ({100 * a / b:.0f}%)"  # noqa: E731

    lines = ["# Retrieval eval results", "",
             f"Generated by `python tools/kb_eval.py`. {n} questions, top {K} results per question, "
             "search engine from KBsearch (`tools/kb.py`).", "",
             "| | " + " | ".join(sums) + " |", "|---|" + "---|" * len(sums),
             "| Articles in the index | " + " | ".join(str(len(d)) for d in conditions().values()) + " |",
             "| Right article first (hit@1) | " + " | ".join(pct(s["hit1"]) for s in sums.values()) + " |",
             "| Right article in top 3 (hit@3) | " + " | ".join(pct(s["hit3"]) for s in sums.values()) + " |",
             "| Chance of hit@1 by random pick | " + " | ".join(f"{100 * s['chance1']:.0f}%" for s in sums.values()) + " |",
             "| Stale page returned first | " + " | ".join(pct(s["stale1"]) for s in sums.values()) + " |",
             "| Words in the top result (mean) | " + " | ".join(f"{s['words1']:.0f}" for s in sums.values()) + " |",
             "| Share of those words about the question, when right | " + " | ".join(f"{100 * s['relevant_share_when_hit']:.0f}%" for s in sums.values()) + " |",
             "| Top result usable as-is (right, numbered steps, escalation rule) | " + " | ".join(pct(s["usable1"]) for s in sums.values()) + " |",
             "", "## Hit@1 by question style", "",
             "| Style | " + " | ".join(sums) + " |", "|---|" + "---|" * len(sums)]
    for style in ("plain", "vague", "typo", "code"):
        cells = [f"{s['by_style'][style][0]}/{s['by_style'][style][1]}" for s in sums.values()]
        lines.append(f"| {style} | " + " | ".join(cells) + " |")
    lines += ["", "## Misses", ""]
    for name, rows in results.items():
        misses = [r for r in rows if not r["hit1"]]
        lines.append(f"**{name}** ({len(misses)})" + ("" if misses else ": none"))
        q_by_id = {q["id"]: q["question"] for q in questions}
        for r in misses:
            tag = " (stale page)" if r["stale1"] else ""
            lines.append(f"- Q{r['id']} \"{q_by_id[r['id']]}\" -> {r['top1']}{tag}")
        lines.append("")

    (ROOT / "eval" / "results.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    with open(ROOT / "eval" / "results_per_question.csv", "w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["condition", "id", "style", "issue_id", "hit1", "hit3", "stale1", "top1"])
        for name, rows in results.items():
            for r in rows:
                w.writerow([name, r["id"], r["style"], r["issue_id"], int(r["hit1"]), int(r["hit3"]),
                            int(r["stale1"]), r["top1"]])
    print("\n".join(lines[:16]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
